//! `aix sync`: regenerates derived files from the track directories and README curriculum.
//!
//! * `crates/ai-candle/src/lib.rs` and `crates/ai-kernel/src/lib.rs` topic module trees
//! * `crates/ai-candle/tests/<category>.rs` integration-test aggregators
//! * README checklist marks (derived from which track files exist) and the progress table

use std::collections::BTreeMap;
use std::fmt::Write as _;
use std::fs;

use crate::curriculum::{self, block, Readme, Status, README};
use crate::repo::{file_name, match_eol, strip_num, Repo, CATEGORIES, TRACKS};

pub const BEGIN_TAG: &str = "<aix:generated>";
pub const END_TAG: &str = "</aix:generated>";

pub struct Output {
    pub path: String,
    pub content: String,
}

/// Status implied by the files on disk, plus the tracks that are still missing.
pub fn derived(repo: &Repo, id: &str) -> (Status, Vec<&'static str>) {
    let missing: Vec<&'static str> = TRACKS
        .iter()
        .filter(|(t, e)| !repo.files.contains(&format!("{t}/{id}.{e}")))
        .map(|(t, _)| *t)
        .collect();
    let status = match missing.len() {
        0 => Status::Done,
        n if n == TRACKS.len() => Status::Planned,
        _ => Status::Wip,
    };
    (status, missing)
}

/// Module name for the i-th (0-based) topic of a category: `tNN_<slug without number>`.
pub fn module_name(index: usize, id: &str) -> String {
    format!("t{:02}_{}", index + 1, strip_num(file_name(id)))
}

/// Topics of `category` present in `track`, in module order.
pub fn category_topics(repo: &Repo, track: &str, category: &str) -> Vec<String> {
    let prefix = format!("{category}/");
    repo.track_topics(track)
        .into_iter()
        .filter(|id| id.starts_with(&prefix))
        .collect()
}

fn crate_region(repo: &Repo, track: &str) -> String {
    let mut s = String::new();
    for cat in CATEGORIES {
        let ids = category_topics(repo, track, cat);
        if ids.is_empty() {
            continue;
        }
        let _ = writeln!(s, "#[path = \"../../../{track}/{cat}\"]");
        let _ = writeln!(s, "pub mod c{cat} {{");
        for (i, id) in ids.iter().enumerate() {
            if i > 0 {
                s.push('\n');
            }
            let _ = writeln!(s, "    #[path = \"{}.rs\"]", &id[cat.len() + 1..]);
            let _ = writeln!(s, "    pub mod {};", module_name(i, id));
        }
        s.push_str("}\n\n");
    }
    s
}

fn aggregator_region(repo: &Repo, category: &str) -> Option<String> {
    let dir = format!("crates/ai-candle/tests/{category}");
    let stems: Vec<String> = repo
        .files_with(&dir, "rs")
        .filter(|f| f.matches('/').count() == 4 && file_name(f).starts_with("test_"))
        .map(|f| file_name(f).trim_end_matches(".rs").to_string())
        .collect();
    if stems.is_empty() {
        return None;
    }
    let mut s = String::new();
    for (i, stem) in stems.iter().enumerate() {
        if i > 0 {
            s.push('\n');
        }
        let _ = writeln!(s, "#[path = \"{category}/{stem}.rs\"]");
        let _ = writeln!(s, "mod {stem};");
    }
    Some(s)
}

/// Replaces the generated region of `original` (between marker comments). On first use the region
/// is taken to start at the first line beginning with `first_line_prefix` and run to end of file.
fn splice(original: &str, region: &str, first_line_prefix: &str) -> String {
    let orig = original.replace("\r\n", "\n");
    let begin_line = format!("// {BEGIN_TAG} Generated by `cargo aix sync` from the track directories. Do not edit by hand.");
    let end_line = format!("// {END_TAG}");
    let (head, tail): (String, String) = match (orig.find(BEGIN_TAG), orig.find(END_TAG)) {
        (Some(b), Some(e)) if b < e => {
            let head_end = orig[..b].rfind('\n').map(|i| i + 1).unwrap_or(0);
            let after = &orig[e..];
            let tail_start = after.find('\n').map(|i| i + 1).unwrap_or(after.len());
            (
                orig[..head_end].to_string(),
                after[tail_start..].to_string(),
            )
        }
        _ => {
            let at = if orig.starts_with(first_line_prefix) {
                Some(0)
            } else {
                orig.find(&format!("\n{first_line_prefix}")).map(|i| i + 1)
            };
            match at {
                Some(p) => (orig[..p].to_string(), String::new()),
                None if orig.trim().is_empty() => (String::new(), String::new()),
                None => (format!("{}\n\n", orig.trim_end()), String::new()),
            }
        }
    };
    let out = format!(
        "{head}{begin_line}\n\n{}\n{end_line}\n{tail}",
        region.trim_end()
    );
    match_eol(original, &out)
}

fn category_number_title(cat: &str) -> String {
    let (num, rest) = cat.split_at(2);
    let words: Vec<String> = rest
        .trim_start_matches('_')
        .split('_')
        .map(|w| {
            let mut c = w.chars();
            c.next()
                .map(|f| f.to_uppercase().collect::<String>() + c.as_str())
                .unwrap_or_default()
        })
        .collect();
    format!("{num} {}", words.join(" "))
}

fn update_progress_badge(text: &str, done: usize, target: usize) -> String {
    let prefix = "https://img.shields.io/badge/Progress-";
    let suffix = "%20Topics-blue.svg";
    let mut out = String::with_capacity(text.len());
    let mut rest = text;
    while let Some(b) = rest.find(prefix) {
        out.push_str(&rest[..b]);
        let after_prefix = &rest[b + prefix.len()..];
        if let Some(e) = after_prefix.find(suffix) {
            let mid = &after_prefix[..e];
            if mid
                .chars()
                .all(|c| c.is_ascii_digit() || c == '%' || c == '2' || c == 'F')
            {
                let _ = write!(out, "{prefix}{done}%2F{target}{suffix}");
                rest = &after_prefix[e + suffix.len()..];
                continue;
            }
        }
        out.push_str(prefix);
        rest = after_prefix;
    }
    out.push_str(rest);
    out
}

fn readme_output(repo: &Repo, readme: &Readme) -> (String, usize, usize) {
    let raw = &readme.raw;
    let mut ls: Vec<String> = curriculum::lines(raw)
        .into_iter()
        .map(str::to_string)
        .collect();

    // 1. Checklist marks follow the files on disk.
    let mut counts: BTreeMap<String, [usize; 3]> = BTreeMap::new();
    for t in &readme.topics {
        let (status, _) = derived(repo, &t.id);
        counts.entry(t.category().to_string()).or_default()[status as usize] += 1;
        let line = &mut ls[t.line];
        if let Some(i) = line.find("- [") {
            let at = i + 3;
            if line[at..].chars().next() != Some(status.mark()) {
                let old_len = line[at..].chars().next().map(char::len_utf8).unwrap_or(1);
                line.replace_range(at..at + old_len, &status.mark().to_string());
            }
        }
    }

    let mut tot = [0usize; 3];
    for cat in CATEGORIES {
        let c = counts.get(cat).copied().unwrap_or_default();
        for k in 0..3 {
            tot[k] += c[k];
        }
    }
    let listed: usize = tot.iter().sum();
    let target = readme.contract.target_topics.unwrap_or(listed).max(listed);

    // 2. Progress table.
    let view: Vec<&str> = ls.iter().map(String::as_str).collect();
    if let Some((b, e)) = block(&view, "progress") {
        let mut table = vec![
            String::new(),
            "| Category | Done | WIP | Planned | Listed |".to_string(),
            "|---|---:|---:|---:|---:|".to_string(),
        ];
        for cat in CATEGORIES {
            let c = counts.get(cat).copied().unwrap_or_default();
            table.push(format!(
                "| [{}](#{cat}) | {} | {} | {} | {} |",
                category_number_title(cat),
                c[2],
                c[1],
                c[0],
                c.iter().sum::<usize>()
            ));
        }
        table.push(format!(
            "| **Total** | **{}** | **{}** | **{}** | **{listed}** |",
            tot[2], tot[1], tot[0]
        ));
        table.push(String::new());
        let pct = if target > 0 {
            100.0 * tot[2] as f64 / target as f64
        } else {
            0.0
        };
        table.push(format!(
            "**{} / {target} topics complete ({pct:.0}%)** across all 7 tracks. {} topic(s) of the target are not yet listed with a slug in the curriculum below.",
            tot[2],
            target - listed
        ));
        table.push(String::new());
        table.push("_Generated by `cargo aix sync`. A topic is **done** when all 7 track files exist, **wip** when some do._".to_string());
        table.push(String::new());
        ls.splice(b + 1..e, table);
    }
    let joined = update_progress_badge(&ls.join("\n"), tot[2], target);
    (match_eol(raw, &joined), tot[2], target)
}

/// Computes the desired content of every derived file.
pub fn generate(repo: &Repo, readme: &Readme) -> Vec<Output> {
    let mut outs = Vec::new();
    for (path, track) in [
        ("crates/ai-candle/src/lib.rs", "candle"),
        ("crates/ai-kernel/src/lib.rs", "kernels"),
    ] {
        let original = repo.read(path).unwrap_or_default();
        let content = splice(
            &original,
            &crate_region(repo, track),
            &format!("#[path = \"../../../{track}/"),
        );
        outs.push(Output {
            path: path.to_string(),
            content,
        });
    }
    for cat in CATEGORIES {
        let Some(region) = aggregator_region(repo, cat) else {
            continue;
        };
        let path = format!("crates/ai-candle/tests/{cat}.rs");
        let original = repo.read(&path).unwrap_or_else(|_| {
            format!(
                "//! Category {} Integration Test Suite for ai-candle.\n\n",
                category_number_title(cat)
            )
        });
        let content = splice(&original, &region, &format!("#[path = \"{cat}/"));
        outs.push(Output { path, content });
    }
    let (readme_content, done, target) = readme_output(repo, readme);
    outs.push(Output {
        path: README.to_string(),
        content: readme_content,
    });
    if let Ok(idx_raw) = repo.read("INDEX_BY_GOAL.md") {
        let idx_updated = update_progress_badge(&idx_raw, done, target);
        outs.push(Output {
            path: "INDEX_BY_GOAL.md".to_string(),
            content: idx_updated,
        });
    }
    outs
}

/// Outputs whose content differs from disk.
pub fn stale(repo: &Repo, outputs: &[Output]) -> Vec<String> {
    outputs
        .iter()
        .filter(|o| {
            repo.read(&o.path)
                .map(|cur| cur != o.content)
                .unwrap_or(true)
        })
        .map(|o| o.path.clone())
        .collect()
}

/// Writes changed outputs; returns the changed paths.
pub fn write(repo: &Repo, outputs: &[Output]) -> Result<Vec<String>, String> {
    let changed = stale(repo, outputs);
    for o in outputs.iter().filter(|o| changed.contains(&o.path)) {
        let abs = repo.abs(&o.path);
        if let Some(dir) = abs.parent() {
            fs::create_dir_all(dir).map_err(|e| format!("{}: {e}", o.path))?;
        }
        fs::write(&abs, &o.content).map_err(|e| format!("{}: {e}", o.path))?;
    }
    Ok(changed)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn splice_is_idempotent_and_preserves_head() {
        let original = "//! doc\n\npub mod context;\n\n#[path = \"../../../kernels/00_a\"]\npub mod c00_a {}\n\n\n";
        let region = "#[path = \"../../../kernels/00_a\"]\npub mod c00_a {\n}\n\n";
        let once = splice(original, region, "#[path = \"../../../kernels/");
        assert!(once.starts_with("//! doc\n\npub mod context;\n\n// <aix:generated>"));
        assert_eq!(splice(&once, region, "#[path = \"../../../kernels/"), once);
    }

    #[test]
    fn module_names() {
        assert_eq!(module_name(11, "05_a/03_b/01_rnn_lstm"), "t12_rnn_lstm");
    }
}
